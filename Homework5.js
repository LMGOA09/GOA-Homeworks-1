// A while loop is a control flow statement in JavaScript that repeatedly executes a block of code as long as a 
// specified condition evaluates to true. Before each iteration, the loop checks the condition. Once the condition 
// becomes false, execution stops and moves to the code following the loop

//#2)
// An infinite loop occurs when the loop's stopping condition is never met (it constantly remains true), or when there 
// is no mechanism inside the loop body to update the condition variable. Because the condition never turns false, the 
// program runs endlessly, freezing the browser or crashing the execution environment.