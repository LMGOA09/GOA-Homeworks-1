# In Python, the 'def' keyword stands for "define". It is used to create a 
# user-defined function. A function is a self-contained, reusable block of code 
# that only runs when it is called. 

# What they are used for:
# 1. Reusability: Instead of writing the same code multiple times, you write it 
#    once inside a function and call it whenever you need it.
# 2. Organization: They break down large, complex programs into smaller, 
#    manageable, and organized chunks (modular programming).
# 3. Readability & Maintenance: It makes code easier to read and debug. If a bug 
#    occurs, you only have to fix it inside the function rather than in 
#    multiple places across your script.
# 4. Abstraction: It allows you to use a piece of code without needing to 
#    constantly remember exactly how it works inside—you just care about what 
#    it takes in (inputs/arguments) and what it gives back (outputs/return values).